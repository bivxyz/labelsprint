import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "data", "avery-templates.json");
const webOutputPath = path.join(root, "src", "generatedAveryTemplates.js");
const workspaceOutputPath = path.join(root, "workspace-extension", "TemplateCatalog.gs");
const checkOnly = process.argv.includes("--check");

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.templates)) {
  throw new Error("data/avery-templates.json must use schemaVersion 1 and contain a templates array.");
}

const normalizedIds = new Map();
for (const template of manifest.templates) {
  validateTemplate(template);
  for (const code of [template.id, ...(template.aliases || [])]) {
    const normalized = normalizeCode(code);
    const owner = normalizedIds.get(normalized);
    if (owner && owner !== template.id) throw new Error(`Duplicate template SKU or alias: ${code}`);
    normalizedIds.set(normalized, template.id);
  }
}

const sorted = [...manifest.templates].sort((a, b) =>
  String(a.id).localeCompare(String(b.id), undefined, { numeric: true }),
);
const webOutput = renderWebOutput(sorted);
const workspaceOutput = renderWorkspaceOutput(sorted);

if (checkOnly) {
  await assertCurrent(webOutputPath, webOutput);
  await assertCurrent(workspaceOutputPath, workspaceOutput);
  console.log(`Template outputs are current (${sorted.length} calibrated layouts).`);
} else {
  await writeFile(webOutputPath, webOutput, "utf8");
  await writeFile(workspaceOutputPath, workspaceOutput, "utf8");
  console.log(`Generated web and Workspace catalogs for ${sorted.length} calibrated layouts.`);
}

function normalizeCode(value) {
  return String(value || "").replace(/[^A-Za-z0-9-]/g, "").toUpperCase().replace(/^0+(?=\d)/, "");
}

function validateTemplate(template) {
  for (const key of ["id", "category", "shape", "name", "description"]) {
    if (!String(template[key] || "").trim()) throw new Error(`Template ${template.id || "?"} is missing ${key}.`);
  }
  for (const key of ["w", "h", "rows", "cols", "top", "left", "hGap", "vGap"]) {
    if (!Number.isFinite(template[key]) || template[key] < 0) {
      throw new Error(`Template ${template.id} has an invalid ${key}.`);
    }
  }
  if (!Number.isInteger(template.rows) || !Number.isInteger(template.cols) || template.rows < 1 || template.cols < 1) {
    throw new Error(`Template ${template.id} must have positive integer rows and columns.`);
  }
  if (template.pageSize !== "Letter") throw new Error(`Template ${template.id} is not a Letter layout.`);

  const usedWidth = template.cols * template.w + Math.max(0, template.cols - 1) * template.hGap;
  const usedHeight = template.rows * template.h + Math.max(0, template.rows - 1) * template.vGap;
  if (template.left + usedWidth > 8.501 || template.top + usedHeight > 11.001) {
    throw new Error(`Template ${template.id} extends beyond Letter paper.`);
  }
}

function renderWebOutput(templates) {
  return `// Generated by tools/generate-template-outputs.mjs. Do not edit directly.\n` +
    `export const GENERATED_AVERY_TEMPLATES = Object.freeze(${JSON.stringify(templates, null, 2)}.map(Object.freeze));\n`;
}

function renderWorkspaceOutput(templates) {
  const rows = templates.map((template) => {
    const args = [
      template.id, template.name, template.category, template.description,
      template.w, template.h, template.rows, template.cols,
      template.top, template.left, template.hGap, template.vGap,
      template.aliases || [],
    ].map((value) => JSON.stringify(value));
    return `  ${JSON.stringify(template.id)}: createWorkspaceTemplate_(${args.join(", ")})`;
  });

  return `// Generated by tools/generate-template-outputs.mjs. Do not edit directly.\n` +
`const LABELSPRINT_TEMPLATES = Object.freeze({\n${rows.join(",\n")}\n});\n\n` +
`function createWorkspaceTemplate_(id, name, category, description, widthIn, heightIn, rows, columns, topIn, leftIn, horizontalGapIn, verticalGapIn, aliases) {\n` +
`  return Object.freeze({\n` +
`    id: id,\n    name: name,\n    category: category,\n    description: description,\n` +
`    widthIn: widthIn,\n    heightIn: heightIn,\n    rows: rows,\n    columns: columns,\n` +
`    topIn: topIn,\n    leftIn: leftIn,\n    horizontalGapIn: horizontalGapIn,\n    verticalGapIn: verticalGapIn,\n` +
`    aliases: aliases || [],\n    labelsPerSheet: rows * columns\n  });\n}\n\n` +
`function getWorkspaceTemplate_(templateId) {\n` +
`  const normalized = String(templateId || '').replace(/\\D/g, '');\n` +
`  if (LABELSPRINT_TEMPLATES[normalized]) return LABELSPRINT_TEMPLATES[normalized];\n\n` +
`  const ids = Object.keys(LABELSPRINT_TEMPLATES);\n` +
`  for (let index = 0; index < ids.length; index += 1) {\n` +
`    const template = LABELSPRINT_TEMPLATES[ids[index]];\n` +
`    if (template.aliases.indexOf(normalized) >= 0) return template;\n  }\n\n` +
`  return LABELSPRINT_TEMPLATES['5160'];\n}\n`;
}

async function assertCurrent(filePath, expected) {
  let actual = "";
  try {
    actual = await readFile(filePath, "utf8");
  } catch {
    throw new Error(`${path.relative(root, filePath)} has not been generated.`);
  }
  if (actual !== expected) {
    throw new Error(`${path.relative(root, filePath)} is stale. Run npm run templates:generate.`);
  }
}
